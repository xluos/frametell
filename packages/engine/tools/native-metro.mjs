// Authoring bridge: the original Python engine computes layout; the browser only seeks its original SVG animation.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const engine = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envDir = path.join(engine, 'native/python/.venv');
const python = path.join(envDir, process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
const args = process.argv.slice(2);
try {
  if (args.includes('--setup')) {
    if (!fs.existsSync(python)) {
      const uv = spawnSync('uv', ['--version'], { encoding: 'utf8' });
      if (uv.status === 0) execFileSync('uv', ['venv', '--python', '3.12', envDir], { stdio: 'inherit' });
      else execFileSync('python3', ['-m', 'venv', envDir], { stdio: 'inherit' });
    }
    if (spawnSync('uv', ['--version']).status === 0) execFileSync('uv', ['pip', 'install', '--python', python, '-r', path.join(engine, 'native/python/requirements.txt')], { stdio: 'inherit' });
    else execFileSync(python, ['-m', 'pip', 'install', '-r', path.join(engine, 'native/python/requirements.txt')], { stdio: 'inherit' });
    console.log('nf-metro 2.1.0 ready');
  } else {
    const input = args[0], page = args[args.indexOf('--page') + 1];
    if (!input || !args.includes('--page') || !/^p[\w-]+$/.test(page)) throw new Error('Usage: node engine/tools/native-metro.mjs materials/p01.mmd --page p01 [--theme light|dark]');
    if (!fs.existsSync(python)) throw new Error('nf-metro is not installed. Run: node engine/tools/native-metro.mjs --setup');
    const version = execFileSync(python, ['-c', 'from importlib.metadata import version; print(version("nf-metro"))'], { encoding: 'utf8' }).trim();
    if (version !== '2.1.0') throw new Error(`Expected nf-metro 2.1.0, found ${version}; rerun --setup`);
    const root = fs.realpathSync('.'), source = fs.realpathSync(input);
    if (!source.startsWith(root + path.sep) || !source.endsWith('.mmd')) throw new Error('Input must be a .mmd file inside this project');
    const theme = args.includes('--theme') ? args[args.indexOf('--theme') + 1] : 'light';
    if (!['light', 'dark'].includes(theme)) throw new Error('Theme must be light or dark');
    const tmp = fs.mkdtempSync(path.join(root, '.native-metro-'));
    try {
      const output = path.join(tmp, 'map.svg');
      execFileSync(python, ['-m', 'nf_metro', 'render', source, '-o', output, '--animate', '--theme', theme], { encoding: 'utf8', timeout: 120_000, maxBuffer: 16 << 20 });
      const svg = fs.readFileSync(output, 'utf8');
      if (!svg.includes('diagram-manifest') || !svg.includes('<svg')) throw new Error('nf-metro produced no diagram manifest');
      const target = path.join(root, 'pages'); fs.mkdirSync(target, { recursive: true });
      if (fs.realpathSync(target) !== target) throw new Error('pages/ must be a real project directory');
      // Rename replaces an existing page symlink itself; it never follows it when installing generated code.
      const pending = path.join(target, `.${page}.${process.pid}.tmp`);
      fs.writeFileSync(pending, `// Generated by nf-metro ${version} from ${path.relative(root,source)}.\nENGINE.visual(${JSON.stringify(page)}, P => {\n  P.nativeScene((N, host) => N.mount(host, ${JSON.stringify(svg)}));\n});\n`, { flag: 'wx' });
      fs.renameSync(pending, path.join(target, `${page}.js`));
      console.log(`nf-metro ${version}: ${path.relative(root,source)} -> pages/${page}.js`);
    } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
  }
} catch (e) { console.error(e.message); process.exitCode = 1; }
